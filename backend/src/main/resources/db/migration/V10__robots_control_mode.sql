-- 로봇 제어 모드 (S15P11A301-350).
--
-- 젯슨은 `ROBOT_STATE.controlMode` 를 1Hz 로 계속 보내왔고 `RobotStateData` 가 그것을
-- 파싱까지 했는데, **읽는 코드가 한 줄도 없어 버려지고 있었다.** 2026-08-08 실기동에서
-- 그 대가가 드러났다 — 폰이 모터 보드를 수동으로 승격시킨 21:04 부터 14분간 관제 화면은
-- 「자율」 토글을 보여줬고, 그 사이 「탐사 시작」이 두 번 거부됐다.
--
-- **왜 `missions` 가 아니라 `robots` 인가.** 제어 모드는 임무 유무와 무관하게 존재하며
-- 로봇당 하나다. 종전에 관제가 모드를 아는 유일한 길은 `missions.status` 였는데
-- (`RobotStateWriter` 가 쓰고 프런트가 거기서 파생했다), 그 경로는 `ended_at IS NULL`
-- 가드가 지킨다 — 옳은 가드다. 종료된 임무를 되살리면 안 되기 때문이다. 문제는 임무가
-- 닫힌 뒤에 수동으로 들어가면 **옮겨 적을 곳이 아예 없다**는 것이었다. 위 실기동이
-- 정확히 그 경우다(21:03:03 임무 종료 → 21:04:14 수동 진입).
--
-- `missions.status` 의 12값에도 'MANUAL' 이 있어 문자열이 겹쳐 보이지만 **다른 상태
-- 공간이다.** 그쪽은 임무 상태 머신(26.2)이고 이쪽은 제어 권한이다. 한쪽을 다른 쪽에서
-- 파생시키려 하면 이번 버그로 돌아온다.
--
-- **NULL 을 허용하는 것은 의도다.** 3값이 필요하다 — MANUAL / AUTO / NULL(모름: 아직
-- 보고받지 못했거나 mission_manager 가 안 떠 있다). `NOT NULL DEFAULT 'AUTO'` 로 두면
-- 「아직 아무 보고도 못 받은 로봇」과 「자율로 확인된 로봇」이 같은 값이 되고, 관제는
-- 모드를 알 수 없는 상황을 정상 자율로 표시한다 — 고치려는 증상 그대로다.
-- `mcu_connected`(V5)·`recorder_ok`(V8)·`motor_link_ok`(V9)가 세운 규칙과 같다.
--
-- CHECK 제약을 넣지 않는다. V1 전체에 CHECK 가 하나도 없고 값 검증은 Java 상수 집합이
-- 맡는다. 제약을 걸면 젯슨이 모드를 하나 더 늘렸을 때 INSERT 가 통째로 실패해 같은
-- 메시지의 다른 필드까지 유실된다.
ALTER TABLE robots ADD COLUMN IF NOT EXISTS control_mode VARCHAR(16);
